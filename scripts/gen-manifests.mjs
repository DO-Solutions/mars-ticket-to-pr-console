// Inline the agent manifests and prompt templates into a TS module at build
// time. The Guardrails pane renders these, so what a client sees on screen is
// the exact policy the agents ran under — not a copy that can drift.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(root, p), 'utf8');

const files = {
  fixerManifest: 'agents/fixer.yaml',
  reviewerManifest: 'agents/reviewer.yaml',
  fixerPrompt: 'prompts/fixer.tmpl',
  reviewerPrompt: 'prompts/reviewer.tmpl',
};

const entries = Object.entries(files)
  .map(([k, p]) => `export const ${k} = ${JSON.stringify(read(p))};`)
  .join('\n\n');

writeFileSync(
  join(root, 'lib/manifests.generated.ts'),
  `// GENERATED by scripts/gen-manifests.mjs — do not edit.\n// Source of truth: ${Object.values(files).join(', ')}\n\n${entries}\n`,
);

console.log('generated lib/manifests.generated.ts');
