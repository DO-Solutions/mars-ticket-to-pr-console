// Inline the agent manifests, prompt templates and the skill bodies into a TS
// module at build time. The Agents tab renders these, so what a client sees on
// screen is the exact policy and playbook the agents ran under — not a copy
// that can drift.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(root, p), 'utf8');

const files = {
  fixerManifest: 'agents/fixer.yaml',
  reviewerManifest: 'agents/reviewer.yaml',
  fixerPrompt: 'prompts/fixer.tmpl',
  reviewerPrompt: 'prompts/reviewer.tmpl',
};

/**
 * Pull the `instructions: |` block out of a manifest's skill.
 *
 * The playbook is the most useful text in the repo and the least readable in
 * situ, buried under six spaces of YAML indentation. Extracting it lets the UI
 * render it as the markdown it already is, while the manifest stays the single
 * source of truth.
 */
function extractSkill(yaml) {
  const lines = yaml.split('\n');
  const start = lines.findIndex((l) => /^\s*instructions:\s*\|/.test(l));
  if (start === -1) return { name: '', description: '', body: '' };

  const indent = (lines[start].match(/^\s*/) ?? [''])[0].length + 2;
  const body = [];
  for (const line of lines.slice(start + 1)) {
    if (line.trim() !== '' && (line.match(/^\s*/) ?? [''])[0].length < indent) break;
    body.push(line.slice(indent));
  }

  // The name and description sit just above the instructions block.
  const head = lines.slice(0, start);
  const pick = (key) => {
    for (let i = head.length - 1; i >= 0; i--) {
      // Allow the YAML list-item dash: `  - name: fix-a-taskflow-ticket`.
      const m = head[i].match(new RegExp(`^\\s*-?\\s*${key}:\\s*(.*)$`));
      if (m) return m[1].replace(/^["']|["']$/g, '');
    }
    return '';
  };

  return {
    name: pick('name'),
    description: pick('description'),
    body: body.join('\n').replace(/\n+$/, '\n'),
  };
}

const entries = Object.entries(files)
  .map(([k, p]) => `export const ${k} = ${JSON.stringify(read(p))};`)
  .join('\n\n');

const skills = {
  fixerSkill: extractSkill(read(files.fixerManifest)),
  reviewerSkill: extractSkill(read(files.reviewerManifest)),
};

const skillEntries = Object.entries(skills)
  .map(([k, v]) => `export const ${k} = ${JSON.stringify(v)};`)
  .join('\n\n');

writeFileSync(
  join(root, 'lib/manifests.generated.ts'),
  `// GENERATED by scripts/gen-manifests.mjs — do not edit.\n` +
    `// Source of truth: ${Object.values(files).join(', ')}\n\n${entries}\n\n${skillEntries}\n`,
);

for (const [k, v] of Object.entries(skills)) {
  if (!v.body.trim()) throw new Error(`${k}: no instructions block extracted — check the manifest`);
  console.log(`  ${k}: "${v.name}" (${v.body.split('\n').length} lines)`);
}
console.log('generated lib/manifests.generated.ts');
